package com.qa.api.pojo;

public class UserRequest {
    private String name;
    private String job;

    public UserRequest() { }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getJob() {
        return job;
    }

    public void setJob(String job) {
        this.job = job;
    }
}
